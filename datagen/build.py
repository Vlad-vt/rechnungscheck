"""Build the full synthetic dataset for every tenant.

Committed (small, reviewable): master data, contracts, case manifests with
labels, SHA-256 list of rendered documents.
Not committed (regenerated by ``make data``): the rendered PDFs, XML and PNGs.
"""

from __future__ import annotations

import hashlib
import json
from datetime import UTC, date, datetime
from pathlib import Path

from datagen import catalog
from datagen.contracts import render_contracts
from datagen.masterdata import build_master_data
from datagen.models import Case, Injection, InvoiceHistoryEntry
from datagen.render.cii import render_cii
from datagen.render.pdf import make_zugferd, render_delivery_note_pdf, render_invoice_pdf
from datagen.render.scan import pdf_to_scan
from datagen.render.ubl import render_ubl
from datagen.rng import stream
from datagen.scenarios import generate_cases
from rechnungscheck.domain.invoice import SourceFormat
from rechnungscheck.domain.masterdata import TenantMasterData
from rechnungscheck.tenancy import TenantConfig

DATASET_VERSION = "v1"
DEFAULT_SEED = 42


def _dump(path: Path, data: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")


def write_master_data(tenant_dir: Path, md: TenantMasterData, history: list[InvoiceHistoryEntry]) -> None:
    out = tenant_dir / "master_data"
    for name in ("suppliers", "products", "unit_conversions", "price_agreements"):
        _dump(out / f"{name}.json", [m.model_dump(mode="json") for m in getattr(md, name)])
    _dump(out / "invoice_history.json", [h.model_dump(mode="json") for h in history])


def render_case(case: Case, md: TenantMasterData, seed: int, data_root: Path) -> Case:
    supplier = next(s for s in md.suppliers if s.supplier_id == case.purchase_order.supplier_id)
    lang = supplier.language
    rng = stream(seed, "render", case.case_id)
    rel = Path(case.tenant_id) / case.case_id
    folder = data_root / rel
    folder.mkdir(parents=True, exist_ok=True)
    files: dict[str, str] = {}
    hidden = case.injection_text if case.injection is Injection.HIDDEN else None
    fmt = case.source_format
    if fmt is SourceFormat.XRECHNUNG_CII:
        blob, name = render_cii(case.invoice, lang, "xrechnung"), "invoice.xml"
    elif fmt is SourceFormat.XRECHNUNG_UBL:
        blob, name = render_ubl(case.invoice, lang), "invoice.xml"
    else:
        pdf = render_invoice_pdf(case.invoice, lang, hidden_text=hidden)
        if fmt is SourceFormat.ZUGFERD:
            issued = case.invoice.issue_date.value if case.invoice.issue_date else date(2026, 1, 1)
            stamp = datetime(issued.year, issued.month, issued.day, 12, 0, tzinfo=UTC)
            blob, name = make_zugferd(pdf, render_cii(case.invoice, lang, "en16931"), stamp), "invoice.pdf"
        elif fmt is SourceFormat.TEXT_PDF:
            blob, name = pdf, "invoice.pdf"
        else:
            blob, name = pdf_to_scan(pdf, rng), "invoice.png"
    (folder / name).write_bytes(blob)
    files["invoice"] = (rel / name).as_posix()
    if case.delivery_note is not None:
        buyer = catalog.BUYERS[case.tenant_id].name
        dn_pdf = render_delivery_note_pdf(case.delivery_note, supplier.name, buyer, lang)
        (folder / "delivery_note.pdf").write_bytes(dn_pdf)
        files["delivery_note"] = (rel / "delivery_note.pdf").as_posix()
    return case.model_copy(update={"files": files})


def build_tenant(
    cfg: TenantConfig, tenant_dir: Path, data_root: Path, seed: int = DEFAULT_SEED, render: bool = True
) -> list[Case]:
    md = build_master_data(cfg.tenant_id, seed)
    cases, history = generate_cases(cfg, md, seed)
    write_master_data(tenant_dir, md, history)
    contracts_dir = tenant_dir / "contracts"
    contracts_dir.mkdir(parents=True, exist_ok=True)
    for fname, text in render_contracts(cfg, catalog.BUYERS[cfg.tenant_id].name, md).items():
        (contracts_dir / fname).write_text(text, encoding="utf-8", newline="\n")
    if render:
        cases = [render_case(c, md, seed, data_root) for c in cases]
    evals = tenant_dir / "evals"
    evals.mkdir(parents=True, exist_ok=True)
    with (evals / "cases.jsonl").open("w", encoding="utf-8", newline="\n") as fh:
        for c in cases:
            fh.write(c.model_dump_json(exclude_none=True) + "\n")
    if render:
        lines = []
        for c in cases:
            for path in sorted(c.files.values()):
                digest = hashlib.sha256((data_root / path).read_bytes()).hexdigest()
                lines.append(f"{digest}  {path}")
        (evals / "documents.sha256").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    _dump(
        evals / "dataset.json",
        {
            "version": DATASET_VERSION,
            "seed": seed,
            "cases": len(cases),
            "dev": sum(1 for c in cases if c.split.value == "dev"),
            "test": sum(1 for c in cases if c.split.value == "test"),
        },
    )
    return cases
